import { RobotModel } from '../../types/robot';
import { CodeExportOptions } from '../../types/codeExport';
import { PUMA560_INERTIA } from '../../physics/RNEEngine';

export function generateUrdfCode(
  robot: RobotModel,
  _currentAnglesDeg: number[],
  options: CodeExportOptions
): string {
  const d2r = (deg: number) => (deg * Math.PI) / 180;

  let xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- ========================================================================= -->
<!-- Unified Robot Description Format (URDF)                                   -->
<!-- Robot: ${robot.name} (${robot.manufacturer}) - ${robot.dof} Degrees of Freedom -->
<!-- Generated by RoboCAD 3D - Multi-Platform Code Exporter                    -->
<!-- Fully compliant with ROS 1 / ROS 2 (Humble, Iron, Jazzy) / RViz2 / Gazebo -->
<!-- ========================================================================= -->

<robot name="${robot.id.toLowerCase()}">

  <!-- Materials Definition -->
  <material name="industrial_dark">
    <color rgba="0.15 0.17 0.20 1.0"/>
  </material>
  <material name="robot_accent">
    <color rgba="0.10 0.45 0.90 1.0"/>
  </material>
  <material name="tool_metal">
    <color rgba="0.80 0.82 0.85 1.0"/>
  </material>

  <!-- World / Base Footprint Link -->
  <link name="base_link">
    <visual>
      <origin xyz="0 0 0.05" rpy="0 0 0"/>
      <geometry>
        <cylinder radius="0.18" length="0.10"/>
      </geometry>
      <material name="industrial_dark"/>
    </visual>
    <collision>
      <origin xyz="0 0 0.05" rpy="0 0 0"/>
      <geometry>
        <cylinder radius="0.18" length="0.10"/>
      </geometry>
    </collision>
    <inertial>
      <origin xyz="0 0 0.05" rpy="0 0 0"/>
      <mass value="5.0"/>
      <inertia ixx="0.05" ixy="0" ixz="0" iyy="0.05" iyz="0" izz="0.08"/>
    </inertial>
  </link>
`;

  let parentLink = 'base_link';

  robot.joints.forEach((joint, idx) => {
    const linkName = `link_${idx + 1}`;
    const jointName = `joint_${idx + 1}`;

    const thetaOffsetRad = d2r(joint.thetaOffsetDeg);
    const alphaRad = d2r(joint.alphaDeg);
    const aMeters = joint.a / 1000;
    const dMeters = joint.d / 1000;
    const qMinRad = d2r(joint.qMinDeg);
    const qMaxRad = d2r(joint.qMaxDeg);

    // Compute relative origin [x, y, z] from frame i-1
    const x = (aMeters * Math.cos(thetaOffsetRad)).toFixed(5);
    const y = (aMeters * Math.sin(thetaOffsetRad)).toFixed(5);
    const z = dMeters.toFixed(5);
    const roll = alphaRad.toFixed(5);
    const pitch = '0.00000';
    const yaw = thetaOffsetRad.toFixed(5);

    // Inertial parameters
    const inertia =
      robot.id === 'Puma560' && PUMA560_INERTIA[idx]
        ? PUMA560_INERTIA[idx]
        : {
            mass: Math.max(0.5, (robot.totalWeightKg / robot.dof) * (1 - idx * 0.12)),
            com: [0, 0, dMeters / 2],
            inertia: [[0.02, 0, 0], [0, 0.02, 0], [0, 0.02, 0]],
            maxTorque: 100,
          };

    const massVal = inertia.mass.toFixed(3);
    const cx = inertia.com[0].toFixed(4);
    const cy = inertia.com[1].toFixed(4);
    const cz = inertia.com[2].toFixed(4);
    const ixx = inertia.inertia[0][0].toFixed(5);
    const iyy = inertia.inertia[1][1].toFixed(5);
    const izz = inertia.inertia[2][2].toFixed(5);
    const effort = (inertia.maxTorque || 100).toFixed(1);

    // Link visual dimension
    const linkLength = Math.max(0.1, Math.sqrt(aMeters * aMeters + dMeters * dMeters)).toFixed(3);

    xml += `
  <!-- ================= Link ${idx + 1} & Joint ${idx + 1} ================= -->
  <joint name="${jointName}" type="revolute">
    <parent link="${parentLink}"/>
    <child link="${linkName}"/>
    <origin xyz="${x} ${y} ${z}" rpy="${roll} ${pitch} ${yaw}"/>
    <axis xyz="0 0 1"/>
    <limit lower="${qMinRad.toFixed(4)}" upper="${qMaxRad.toFixed(4)}" effort="${effort}" velocity="3.1416"/>
    <dynamics damping="0.1" friction="0.05"/>
  </joint>

  <link name="${linkName}">
    <visual>
      <origin xyz="0 0 ${(-Math.abs(dMeters) / 2).toFixed(4)}" rpy="0 0 0"/>
      <geometry>
        <cylinder radius="0.06" length="${linkLength}"/>
      </geometry>
      <material name="${idx % 2 === 0 ? 'robot_accent' : 'industrial_dark'}"/>
    </visual>
    <collision>
      <origin xyz="0 0 ${(-Math.abs(dMeters) / 2).toFixed(4)}" rpy="0 0 0"/>
      <geometry>
        <cylinder radius="0.06" length="${linkLength}"/>
      </geometry>
    </collision>
`;

    if (options.includeDynamics) {
      xml += `    <inertial>
      <origin xyz="${cx} ${cy} ${cz}" rpy="0 0 0"/>
      <mass value="${massVal}"/>
      <inertia ixx="${ixx}" ixy="0.0" ixz="0.0" iyy="${iyy}" iyz="0.0" izz="${izz}"/>
    </inertial>
`;
    }

    xml += `  </link>
`;

    parentLink = linkName;
  });

  // End-Effector / Flange Link
  xml += `
  <!-- Tool Flange / End-Effector -->
  <joint name="tool_flange_joint" type="fixed">
    <parent link="${parentLink}"/>
    <child link="tool0"/>
    <origin xyz="0 0 0.02" rpy="0 0 0"/>
  </joint>

  <link name="tool0">
    <visual>
      <origin xyz="0 0 0" rpy="0 0 0"/>
      <geometry>
        <cylinder radius="0.03" length="0.01"/>
      </geometry>
      <material name="tool_metal"/>
    </visual>
  </link>

</robot>
`;

  return xml;
}
