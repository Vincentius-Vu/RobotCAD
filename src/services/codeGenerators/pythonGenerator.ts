import { RobotModel } from '../../types/robot';
import { CodeExportOptions } from '../../types/codeExport';
import { PUMA560_INERTIA } from '../../physics/RNEEngine';

export function generatePythonCode(
  robot: RobotModel,
  currentAnglesDeg: number[],
  options: CodeExportOptions
): string {
  const qValsRad = currentAnglesDeg.map((deg) => (deg * Math.PI) / 180);
  const qStr = `[${qValsRad.map((r) => r.toFixed(4)).join(', ')}]`;

  let code = `"""
=============================================================================
Robotics Kinematics & Dynamics Script
Robot Model: ${robot.name} (${robot.manufacturer})
Degrees of Freedom: ${robot.dof}
Generated by RoboCAD 3D - Multi-Platform Code Exporter
Environment: Python 3.8+ with roboticstoolbox-python and spatialmath
=============================================================================
Installation:
    pip install roboticstoolbox-python spatialmath-python numpy matplotlib
=============================================================================
"""

import numpy as np
import roboticstoolbox as rtb
from spatialmath import SE3, SO3
import matplotlib.pyplot as plt

def create_${robot.id.toLowerCase()}_robot():
    """
    Constructs the Denavit-Hartenberg SerialLink model for ${robot.name}.
    DH Parameters: [theta_offset, d (m), a (m), alpha (rad)]
    """
    links = [
`;

  robot.joints.forEach((joint, idx) => {
    const thetaOffsetRad = ((joint.thetaOffsetDeg * Math.PI) / 180).toFixed(5);
    const dMeters = (joint.d / 1000).toFixed(5);
    const aMeters = (joint.a / 1000).toFixed(5);
    const alphaRad = ((joint.alphaDeg * Math.PI) / 180).toFixed(5);
    const qMinRad = ((joint.qMinDeg * Math.PI) / 180).toFixed(4);
    const qMaxRad = ((joint.qMaxDeg * Math.PI) / 180).toFixed(4);

    let inertiaStr = '';
    if (options.includeDynamics) {
      const inertia =
        robot.id === 'Puma560' && PUMA560_INERTIA[idx]
          ? PUMA560_INERTIA[idx]
          : {
              mass: (robot.totalWeightKg / robot.dof) * (1 - idx * 0.12),
              com: [0, 0, (joint.d / 2000)],
              inertia: [[0.05, 0, 0], [0, 0.05, 0], [0, 0.05, 0]],
              maxTorque: 100,
            };

      const m = inertia.mass.toFixed(3);
      const r = `[${inertia.com.map((c) => c.toFixed(3)).join(', ')}]`;
      const Ixx = inertia.inertia[0][0].toFixed(5);
      const Iyy = inertia.inertia[1][1].toFixed(5);
      const Izz = inertia.inertia[2][2].toFixed(5);

      inertiaStr = `,
            m=${m},
            r=${r},
            I=[${Ixx}, ${Iyy}, ${Izz}, 0, 0, 0]`;
    }

    code += `        rtb.RevoluteDH(
            d=${dMeters},
            a=${aMeters},
            alpha=${alphaRad},
            offset=${thetaOffsetRad},
            qlim=[${qMinRad}, ${qMaxRad}]${inertiaStr}
        )${idx < robot.joints.length - 1 ? ',' : ''}
`;
  });

  code += `    ]
    
    robot = rtb.DHRobot(links, name='${robot.name}')
    return robot

def main():
    robot = create_${robot.id.toLowerCase()}_robot()
    print("=" * 60)
    print(f"Loaded Robot: {robot.name}")
    print(robot)
    print("=" * 60)

    # Joint angles configuration (in radians)
    q = np.array(${options.useCurrentAngles ? qStr : 'robot.qz if hasattr(robot, "qz") else np.zeros(robot.n)'})
    print(f"Current Joint Configuration q (rad):\\n{np.round(q, 4)}")
    print(f"Joint Configuration q (deg):\\n{np.round(np.rad2deg(q), 2)}")
`;

  if (options.includeKinematics) {
    code += `
    # -------------------------------------------------------------
    # 1. Forward Kinematics (FK)
    # -------------------------------------------------------------
    T_end_effector = robot.fkine(q)
    print("\\n[1] Forward Kinematics Transformation Matrix T (4x4):")
    print(T_end_effector)
    
    pos = T_end_effector.t
    print(f"TCP Position (X, Y, Z) in meters: {np.round(pos, 4)}")
    print(f"TCP Position in mm: {np.round(pos * 1000, 1)}")

    # -------------------------------------------------------------
    # 2. Numerical Inverse Kinematics (IK)
    # -------------------------------------------------------------
    ik_sol = robot.ikine_LM(T_end_effector)
    print(f"\\n[2] Inverse Kinematics Solution (Levenberg-Marquardt): Success = {ik_sol.success}")
    if ik_sol.success:
        print(f"Calculated q (deg): {np.round(np.rad2deg(ik_sol.q), 2)}")
`;
  }

  if (options.includeJacobian) {
    code += `
    # -------------------------------------------------------------
    # 3. Geometric Jacobian Matrix & Manipulability
    # -------------------------------------------------------------
    J_0 = robot.jacob0(q)
    print("\\n[3] Geometric Jacobian Matrix J0(q) (6xN) in World Frame:")
    print(np.round(J_0, 4))

    # Yoshikawa Manipulability Measure: w = sqrt(det(J * J^T))
    manip = robot.manipulability(q)
    print(f"Yoshikawa Manipulability Index w: {manip:.6f}")
    
    # Condition number: kappa(J) = sigma_max / sigma_min
    cond_num = np.linalg.cond(J_0[:3, :])
    print(f"Translational Jacobian Condition Number: {cond_num:.4f}")
`;
  }

  if (options.includeDynamics) {
    code += `
    # -------------------------------------------------------------
    # 4. Inverse Dynamics (Recursive Newton-Euler Algorithm)
    # -------------------------------------------------------------
    qd = np.zeros(robot.n)       # Joint velocity (rad/s)
    qdd = np.zeros(robot.n)      # Joint acceleration (rad/s^2)
    
    # Gravitational torque vector g(q)
    tau_gravity = robot.gravload(q)
    print("\\n[4] Static Gravity Holding Torques g(q) [N.m]:")
    for i, t in enumerate(tau_gravity):
        print(f"  Joint {i+1}: {t:+.2f} N.m")

    # Joint Inertia Mass Matrix M(q)
    M_q = robot.inertia(q)
    print("\\nJoint Inertia Matrix M(q) (6x6) [kg.m^2]:")
    print(np.round(M_q, 4))

    # Dynamic torques under simulated velocity & acceleration
    qd_sim = np.ones(robot.n) * 0.5   # 0.5 rad/s
    qdd_sim = np.ones(robot.n) * 1.0  # 1.0 rad/s^2
    tau_rne = robot.rne(q, qd_sim, qdd_sim)
    print(f"\\nDynamic Torques tau = M*qdd + C*qd + g [N.m]:\\n{np.round(tau_rne, 2)}")
`;
  }

  if (options.includeVisualization) {
    code += `
    # -------------------------------------------------------------
    # 5. 3D Robotic Visualization
    # -------------------------------------------------------------
    print("\\nLaunching 3D Matplotlib Visualizer...")
    fig = plt.figure(figsize=(9, 7))
    robot.plot(q, block=True)
`;
  }

  code += `
if __name__ == '__main__':
    main()
`;

  return code;
}
